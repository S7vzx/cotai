function request(
  code: number,
  customer: (typeof customers)[number],
  status: string,
  hoursAgo: number,
  items: Item[],
  extra: Record<string, unknown> = {},
) {
  return {
    id: `r${code}`,
    code: `COT-${String(code).padStart(6, '0')}`,
    public_token: `tok${code}`,
    customer_id: customer.id,
    status,
    priority: 'normal',
    assigned_to: null,
    fee_amount: 35,
    fee_discount: 0,
    coupon_id: null,
    payment_status: status === 'aguardando_pagamento' ? 'pendente' : 'pago',
    payment_method: 'pix_manual',
    payment_id: null,
    paid_at: status === 'aguardando_pagamento' ? null : iso(hoursAgo - 0.5),
    paid_confirmed_by: null,
    payment_due_at: iso(-24),
    customer_message: null,
    valid_until: null,
    sent_at: null,
    responded_at: null,
    decline_reason: null,
    fee_deducted: false,
    created_at: iso(hoursAgo),
    updated_at: iso(hoursAgo),
    customers: { name: customer.name, company: customer.company },
    quote_items: items.map((i, idx) => ({
      id: i.id,
      name: i.name,
      quantity: i.quantity,
      target_price: i.target_price,
      quote_item_photos: [{ storage_path: i.photo, position: 0 }],
      position: idx,
    })),
    ...extra,
  }
}

